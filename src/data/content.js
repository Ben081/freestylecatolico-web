export function initials(name) {
  return name
    .replace(/^(Dr\.|Dra\.|Mgtr\.|Lic\.)\s*/, '')
    .split(' ')
    .filter((w) => w[0] === w[0].toUpperCase())
    .slice(0, 2)
    .map((w) => w[0])
    .join('')
}
